import AsyncStorage from '@react-native-async-storage/async-storage';
import React, { useEffect, useState } from 'react';
import { View, Text, StyleSheet, TouchableOpacity, ActivityIndicator, ScrollView, TextInput } from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';
import { router } from 'expo-router';
import { Colors } from '../../constants/Colors';
import { cachedGet } from '../../services/offlineApi';
import { api } from '../../services/api';
import { useTranslation } from 'react-i18next';

interface SiteItem {
  IHS_ID_SITE: string;
  Site_Name: string;
}

export default function SelectSiteTankAudit() {
  const { t } = useTranslation();
  const [sites, setSites] = useState<SiteItem[]>([]);
  const [draftSiteIds, setDraftSiteIds] = useState<Set<string>>(new Set());
  const [loading, setLoading] = useState(false);
  const [isOffline, setIsOffline] = useState(false);
  const [query, setQuery] = useState('');

  useEffect(() => {
    const fetchSitesAndDrafts = async () => {
      try {
        setLoading(true);
        const { data: response, fromCache } = await cachedGet('/technician/tank-audit-sites');
        setIsOffline(fromCache);
        setSites(response?.data || []);

        // Best-effort — if this fails (e.g. offline), the draft badge
        // simply won't show; it never blocks the site list itself.
        try {
          const userStr = await AsyncStorage.getItem('user');
          const userId = userStr ? (JSON.parse(userStr)?.id || JSON.parse(userStr)?._id) : null;
          if (userId) {
            const draftsRes = await api.get('/technician/tank-audits', {
              params: { status: 'draft', createdBy: userId, limit: 200 },
            });
            const ids = new Set<string>((draftsRes.data?.data || []).map((d: any) => d.site_id_ihs));
            setDraftSiteIds(ids);
          }
        } catch {
          // offline or request failed — no draft badges this time, not a hard error
        }
      } catch (error) {
        // handle error
      } finally {
        setLoading(false);
      }
    };
    fetchSitesAndDrafts();
  }, []);

  const filteredSites = sites.filter(s =>
    s.Site_Name?.toLowerCase().includes(query.toLowerCase()) ||
    s.IHS_ID_SITE?.toLowerCase().includes(query.toLowerCase())
  );

  // Sites with a draft in progress surface first, so a technician
  // resuming work doesn't have to scroll to find it.
  const sortedSites = [...filteredSites].sort((a, b) => {
    const aDraft = draftSiteIds.has(a.IHS_ID_SITE) ? 1 : 0;
    const bDraft = draftSiteIds.has(b.IHS_ID_SITE) ? 1 : 0;
    if (aDraft !== bDraft) return bDraft - aDraft;
    return (a.Site_Name || '').localeCompare(b.Site_Name || '');
  });

  return (
    <SafeAreaView style={styles.container}>
      <Text style={styles.title}>{t('select_site_for_tank_audit', 'Select Site for Tank Audit')}</Text>
      {isOffline && (
        <View style={styles.offlineBanner}>
          <Text style={styles.offlineBannerText}>{t('offline_showing_saved_sites', 'Offline — showing last saved sites')}</Text>
        </View>
      )}
      <TextInput
        style={styles.input}
        placeholder={t('search_site_name_or_id', 'Search site name or ID')}
        value={query}
        onChangeText={setQuery}
      />
      {loading ? (
        <ActivityIndicator color={Colors.primary} />
      ) : (
        <ScrollView>
          {sortedSites.map(site => {
            const hasDraft = draftSiteIds.has(site.IHS_ID_SITE);
            return (
              <TouchableOpacity
                key={site.IHS_ID_SITE}
                style={[styles.siteCard, hasDraft && styles.siteCardDraft]}
                onPress={() => router.push({
                  // Expo Router's typed-routes file (.expo/types/router.d.ts) is
                  // generated by watching the filesystem while the dev server or
                  // a build runs — it doesn't know about this route yet because
                  // it was only just added. The file structure here is verified
                  // identical to the existing, working "audit-form" route
                  // ([siteId].tsx under a route-name directory), so this resolves
                  // itself the first time `expo start` runs and regenerates the
                  // types; the cast below isn't masking a real path error.
                  pathname: '/(technician)/tank-audit-form/[siteId]' as any,
                  params: { siteId: site.IHS_ID_SITE, siteName: site.Site_Name },
                })}
              >
                <View style={{ flex: 1 }}>
                  <Text style={styles.siteName}>{site.Site_Name}</Text>
                  <Text style={styles.siteId}>{site.IHS_ID_SITE}</Text>
                </View>
                {hasDraft && (
                  <View style={styles.draftBadge}>
                    <Text style={styles.draftBadgeText}>{t('draft_in_progress', 'Draft — Resume')}</Text>
                  </View>
                )}
              </TouchableOpacity>
            );
          })}
        </ScrollView>
      )}
    </SafeAreaView>
  );
}

const styles = StyleSheet.create({
  container: {
    flex: 1,
    backgroundColor: Colors.background,
    padding: 16,
  },
  title: {
    fontSize: 20,
    fontWeight: 'bold',
    marginBottom: 16,
    color: Colors.text,
  },
  offlineBanner: {
    backgroundColor: '#FEF3C7',
    borderRadius: 8,
    paddingVertical: 6,
    paddingHorizontal: 10,
    marginBottom: 12,
  },
  offlineBannerText: { color: '#92400E', fontSize: 12, fontWeight: '500' },
  input: {
    borderWidth: 1,
    borderColor: Colors.border,
    borderRadius: 8,
    paddingHorizontal: 10,
    paddingVertical: 8,
    color: Colors.text,
    backgroundColor: Colors.background,
    marginBottom: 16,
  },
  siteCard: {
    flexDirection: 'row',
    alignItems: 'center',
    backgroundColor: Colors.surface,
    borderRadius: 8,
    padding: 16,
    marginBottom: 12,
    borderWidth: 1,
    borderColor: Colors.border,
  },
  siteCardDraft: {
    borderColor: '#D97706',
    borderWidth: 1.5,
  },
  siteName: {
    fontSize: 16,
    fontWeight: '600',
    color: Colors.text,
  },
  siteId: {
    marginTop: 4,
    fontSize: 13,
    color: Colors.textSecondary,
  },
  draftBadge: {
    backgroundColor: '#FEF3C7',
    borderRadius: 6,
    paddingVertical: 4,
    paddingHorizontal: 8,
  },
  draftBadgeText: {
    color: '#92400E',
    fontSize: 11,
    fontWeight: '700',
  },
});
